/**
 * Helper to filter recipes by search query with intelligent ranking
 */
export function findMatchingRecipes(query: string, limit: number = 35): SiboRecipe[] {
  if (!query || !query.trim()) return SIBO_MEAL_SUGGESTIONS.slice(0, limit);

  const clean = query.toLowerCase().trim();
  const words = clean.split(/[s,]+/).filter((w) => w.length >= 2);

  const scored = SIBO_MEAL_SUGGESTIONS.map((recipe) => {
    let score = 0;
    const title = recipe.title.toLowerCase();
    const desc = recipe.description.toLowerCase();
    const ings = recipe.ingredients.join(' ').toLowerCase();
    const tag = recipe.tag.toLowerCase();

    if (title.includes(clean)) score += 30;
    if (desc.includes(clean)) score += 15;
    if (ings.includes(clean)) score += 20;
    if (tag.includes(clean)) score += 15;

    for (const w of words) {
      if (title.includes(w)) score += 8;
      if (desc.includes(w)) score += 4;
      if (ings.includes(w)) score += 5;
    }

    return { recipe, score };
  });

  return scored
    .filter((s) => s.score > 0)
    .sort((a, b) => b.score - a.score)
    .map((s) => s.recipe)
    .slice(0, limit);
}
