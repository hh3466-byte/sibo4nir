export function findMatchingRecipes(query: string, limit = 50): SiboRecipe[] {
  if (!query || !query.trim()) return SIBO_MEAL_SUGGESTIONS.slice(0, limit);
  const q = query.trim().toLowerCase();
  return SIBO_MEAL_SUGGESTIONS.filter((r) =>
    r.title.toLowerCase().includes(q) ||
    r.tag.toLowerCase().includes(q) ||
    r.description.toLowerCase().includes(q) ||
    r.ingredients.some((ing) => ing.toLowerCase().includes(q)) ||
    r.instructions.some((ins) => ins.toLowerCase().includes(q))
  ).slice(0, limit);
}
