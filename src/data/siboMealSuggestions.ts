/**
 * Intelligent Recipe Search / Matching Helper for Conversational and SIBO Queries
 */
export function findMatchingRecipes(query: string, limit: number = 35): SiboRecipe[] {
  if (!query || !query.trim()) return [];
  const clean = query.trim().toLowerCase();

  const scored = SIBO_MEAL_SUGGESTIONS.map((recipe) => {
    let score = 0;
    const rTitle = recipe.title.toLowerCase();
    const rDesc = recipe.description.toLowerCase();
    const rIngs = recipe.ingredients.map((i) => i.toLowerCase()).join(" ");
    const rTag = recipe.tag.toLowerCase();

    // Direct category / keyword matches
    if (clean.includes("פרגית") || clean.includes("שיפוד") || clean.includes("שווארמה")) {
      if (rTitle.includes("פרגית") || rTitle.includes("שיפוד") || rTitle.includes("שווארמה") || recipe.id === "l-1" || recipe.id === "l-11") score += 30;
    }
    if (clean.includes("בקר") || clean.includes("סטייק") || clean.includes("קציצ") || clean.includes("בולונז") || clean.includes("אנטרקוט")) {
      if (rTitle.includes("בקר") || rTitle.includes("קציצ") || rTitle.includes("אנטרקוט") || recipe.id === "l-3" || recipe.id === "l-5" || recipe.id === "l-8" || recipe.id === "l-12") score += 25;
    }
    if (clean.includes("דג") || clean.includes("דניס") || clean.includes("לברק") || clean.includes("סלמון") || clean.includes("מוסר") || clean.includes("סרדין") || clean.includes("טונה")) {
      if (rTitle.includes("דניס") || rTitle.includes("לברק") || rTitle.includes("סלמון") || rTitle.includes("מוסר") || rTitle.includes("סרדין") || rTitle.includes("טונה") || recipe.id === "d-2" || recipe.id === "d-3" || recipe.id === "l-6" || recipe.id === "d-5" || recipe.id === "d-6" || recipe.id === "d-7") score += 25;
    }
    if (clean.includes("קומפיר") || clean.includes("תפוח אדמה") || clean.includes("תפו\"א")) {
      if (rTitle.includes("קומפיר") || rTitle.includes("תפוח אדמה") || recipe.id === "l-4") score += 30;
    }
    if (clean.includes("זודלס") || clean.includes("קישוא") || clean.includes("נודלס")) {
      if (rTitle.includes("זודלס") || rTitle.includes("קישוא") || recipe.id === "l-5" || recipe.id === "l-12" || recipe.id === "s-4") score += 25;
    }
    if (clean.includes("דפי אורז") || clean.includes("לאפה") || clean.includes("רול") || clean.includes("פיצה")) {
      if (rTitle.includes("דפי אורז") || rTitle.includes("לאפה") || rTitle.includes("פיצה") || recipe.id === "l-10" || recipe.id === "d-9") score += 30;
    }
    if (clean.includes("פנקייק") || clean.includes("שקדים")) {
      if (rTitle.includes("פנקייק") || recipe.id === "b-5" || recipe.id === "l-9") score += 25;
    }
    if (clean.includes("סניקרס") || clean.includes("שוקולד") || clean.includes("מתוק") || clean.includes("קינוח") || clean.includes("צ׳יה") || clean.includes("צ'יה")) {
      if (rTitle.includes("סניקרס") || rTitle.includes("שוקולד") || rTitle.includes("צ׳יה") || recipe.id === "s-1" || recipe.id === "s-2" || recipe.id === "s-3" || recipe.id === "b-6") score += 25;
    }
    if (clean.includes("מרק") || clean.includes("ציר") || clean.includes("דלורית")) {
      if (rTitle.includes("מרק") || recipe.id === "d-1" || recipe.id === "d-4") score += 25;
    }
    if (clean.includes("ביצ") || clean.includes("חבית") || clean.includes("שקשוקה")) {
      if (rTitle.includes("חבית") || rTitle.includes("שקשוקה") || rTitle.includes("ביצ") || recipe.id === "b-1" || recipe.id === "b-4" || recipe.id === "b-3") score += 20;
    }
    if (clean.includes("גבינ") || clean.includes("פרמזן") || clean.includes("גאודה")) {
      if (rTitle.includes("גבינ") || rTitle.includes("פרמזן") || recipe.id === "d-10" || recipe.id === "b-1" || recipe.id === "l-4") score += 20;
    }

    // Keyword matching
    const tokens = clean.split(/[\s,()]+/).filter((t) => t.length >= 2);
    for (const t of tokens) {
      if (rTitle.includes(t)) score += 6;
      else if (rIngs.includes(t)) score += 3;
      else if (rDesc.includes(t)) score += 2;
      else if (rTag.includes(t)) score += 2;
    }

    return { recipe, score };
  });

  return scored
    .filter((item) => item.score > 0)
    .sort((a, b) => b.score - a.score)
    .map((item) => item.recipe)
    .slice(0, limit);
}
