/**
 * Intelligent Recipe Search / Matching Helper for Conversational and SIBO Queries
 */
export function findMatchingRecipes(query: string, limit: number = 3): SiboRecipe[] {
  if (!query || !query.trim()) return [];
  const clean = query.trim().toLowerCase();

  const scored = SIBO_MEAL_SUGGESTIONS.map((recipe) => {
    let score = 0;
    const rTitle = recipe.title.toLowerCase();
    const rDesc = recipe.description.toLowerCase();
    const rIngs = recipe.ingredients.map((i) => i.toLowerCase()).join(' ');
    const rTag = recipe.tag.toLowerCase();

    // Direct category matches
    if (clean.includes('מרק') || clean.includes('ציר')) {
      if (rTitle.includes('מרק') || recipe.id === 'd-1' || recipe.id === 'd-4') score += 20;
    }
    if (clean.includes('סלט') || clean.includes('חסה') || clean.includes('מלפפון')) {
      if (rTitle.includes('סלט') || recipe.id === 'l-4' || recipe.id === 'd-2') score += 20;
    }
    if (clean.includes('עוף') || clean.includes('פרגית') || clean.includes('שניצל') || clean.includes('הודו')) {
      if (rTitle.includes('עוף') || rIngs.includes('עוף') || recipe.id === 'l-1' || recipe.id === 'd-1' || recipe.id === 'd-3') score += 15;
    }
    if (clean.includes('ביצ') || clean.includes('חבית') || clean.includes('שקשוקה') || clean.includes('בוקר')) {
      if (rTitle.includes('חבית') || rTitle.includes('שקשוקה') || rTitle.includes('ביצ') || recipe.id === 'b-1' || recipe.id === 'b-4' || recipe.id === 'b-3') score += 15;
    }
    if (clean.includes('דג') || clean.includes('סלמון') || clean.includes('דניס') || clean.includes('טונה')) {
      if (rTitle.includes('סלמון') || rTitle.includes('דניס') || rTitle.includes('דג') || recipe.id === 'l-2' || recipe.id === 'd-2' || recipe.id === 'l-4') score += 15;
    }
    if (clean.includes('בשר') || clean.includes('סטייק') || clean.includes('קציצ') || clean.includes('בולונז') || clean.includes('בקר')) {
      if (rTitle.includes('בקר') || rTitle.includes('קציצ') || recipe.id === 'l-3' || recipe.id === 'd-5') score += 15;
    }
    if (clean.includes('קינוח') || clean.includes('מתוק') || clean.includes('שוקולד') || clean.includes('קקאו') || clean.includes('נשנוש')) {
      if (rTitle.includes('שוקו') || rTitle.includes('דייס') || recipe.id === 's-1' || recipe.id === 'b-2') score += 15;
    }
    if (clean.includes('קישוא') || clean.includes('זודלס')) {
      if (rTitle.includes('קישוא') || rIngs.includes('קישוא') || recipe.id === 'l-3' || recipe.id === 'd-4') score += 10;
    }
    if (clean.includes('גזר')) {
      if (rIngs.includes('גזר') || recipe.id === 'd-1' || recipe.id === 'd-4' || recipe.id === 'l-1') score += 10;
    }

    // Keyword matching
    const tokens = clean.split(/[\s,()]+/).filter((t) => t.length >= 2);
    for (const t of tokens) {
      if (rTitle.includes(t)) score += 6;
      else if (rIngs.includes(t)) score += 3;
      else if (rDesc.includes(t)) score += 2;
      else if (rTag.includes(t)) score += 2;
    }

    return { recipe, score };
  });

  return scored
    .filter((item) => item.score > 0)
    .sort((a, b) => b.score - a.score)
    .map((item) => item.recipe)
    .slice(0, limit);
}

